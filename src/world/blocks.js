export const BLOCK_PROPS = [];
for (const [id, name, hex, opts] of DEFS) {
  BLOCK_PROPS[id] = Object.freeze({
    id,
    name,
    solid: !!opts.solid,
    transparent: !!opts.transparent,
    walkable: opts.walkable !== undefined ? !!opts.walkable : !!opts.solid,
    breakable: !!opts.breakable,
    pickable: opts.pickable !== undefined ? !!opts.pickable : !!opts.solid,
    blocksWalk: !!opts.blocksWalk,
    pass: opts.pass || 'opaque',
    shape: opts.shape || 'cube',
    alpha: opts.alpha !== undefined ? opts.alpha : 1.0,
    topY: opts.topY !== undefined ? opts.topY : 1.0,
    emissive: !!opts.emissive,
    hex,
    color: new THREE.Color(hex),
  });
}

const FALLBACK_PROP = BLOCK_PROPS[B.AIR];

export function getBlockProps(id) {
  return BLOCK_PROPS[id] || FALLBACK_PROP;
}

export function blockColor(id) {
  const p = BLOCK_PROPS[id];
  return p ? p.color.clone() : new THREE.Color(0xffffff);
}
